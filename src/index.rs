use std::collections::BTreeMap;
use std::fmt::Write;

use crate::note::{Note, Place};
use crate::vault::{PREFERENCES, PROJECTS, TOPICS, Vault};
use crate::{paging, short_name};

pub const NO_SUMMARY: &str = "(no summary)";

const HEADER: &str = "---
type: index
tags: [agent-memory]
---

# Agent memory index

Generated by petit-poucet from each note's `summary`: do not edit by hand.
";

pub fn generate(vault: &Vault) -> String {
    let full_path = |note: &Note| note.path.clone();
    HEADER.to_string() + &render(&build(vault, |_| true, full_path))
}

pub fn in_session(place: Place, project: Option<&str>) -> bool {
    place == Place::Preferences || project.is_some_and(|p| place == Place::Project(p))
}

#[derive(Clone)]
pub struct Section<'a> {
    pub place: Place<'a>,
    pub title: String,
    pub lines: Vec<String>,
}

// What an agent needs at session start: the preferences, its own project, and only the names of the topics.
pub fn for_project(vault: &Vault, project: Option<&str>) -> String {
    let mut out = render(&sections(vault, |place| in_session(place, project)));
    if let Some(line) = topics_line(vault) {
        write!(out, "\n{line}\n").unwrap();
    }
    out
}

pub fn topics_line(vault: &Vault) -> Option<String> {
    let mut topics: BTreeMap<&str, usize> = BTreeMap::new();
    for note in &vault.notes {
        if let Place::Topic(topic) = note.place() {
            *topics.entry(topic).or_default() += 1;
        }
    }
    let list: Vec<String> = topics.iter().map(|(t, n)| format!("{t} ({n})")).collect();
    (!list.is_empty()).then(|| {
        format!(
            "{TOPICS} (not loaded: memory_search covers them, memory_index with `topic` lists one): {}",
            list.join(", ")
        )
    })
}

pub fn for_topic(vault: &Vault, topic: &str) -> String {
    render(&sections(vault, |place| place == Place::Topic(topic)))
}

// What the model sees: each note by its short name, the section heading already naming the folder.
pub fn sections<'a>(vault: &'a Vault, keep: impl Fn(Place) -> bool) -> Vec<Section<'a>> {
    let names = short_name::all(vault);
    build(vault, keep, |note| names[note.path.as_str()].clone())
}

fn build<'a>(
    vault: &'a Vault,
    keep: impl Fn(Place) -> bool,
    name: impl Fn(&Note) -> String,
) -> Vec<Section<'a>> {
    let mut sections: BTreeMap<Place, Vec<String>> = BTreeMap::new();
    for note in vault.notes.iter().filter(|n| keep(n.place())) {
        let summary = note.summary().unwrap_or(NO_SUMMARY);
        sections
            .entry(note.place())
            .or_default()
            .push(format!("- [[{}]] — {summary}", name(note)));
    }
    sections
        .into_iter()
        .map(|(place, lines)| Section {
            place,
            title: match place {
                Place::Preferences => format!("{PREFERENCES} (all repos)"),
                Place::Project(key) => format!("{PROJECTS} / {key}"),
                Place::Topic(key) => format!("{TOPICS} / {key}"),
            },
            lines,
        })
        .collect()
}

pub fn heading(title: &str) -> String {
    format!("\n## {title}\n")
}

fn page_footer(page: usize, total: usize) -> String {
    match page < total {
        true => format!(
            "(page {page} of {total}: call memory_index again with page={} for the next page.)",
            page + 1
        ),
        false => format!("(page {page} of {total}, the last.)"),
    }
}

const SHORT_HEAD: &str =
    "Agent memory (petit-poucet) Index: the rules did not fit this page budget.\n";
const CONFLICTS_TITLE: &str = "Sync conflicts (older copies)";

// Index order; a page that continues a section repeats its heading, and a line longer than a page is split between characters.
pub fn pages(
    sections: &[Section],
    topics: Option<&str>,
    conflicts: &[String],
    head: &str,
    max: usize,
) -> Vec<String> {
    let reserve = page_footer(usize::MAX - 1, usize::MAX).len() + 1;
    let head = if head.len() + reserve <= max {
        head
    } else {
        SHORT_HEAD
    };
    let items: Vec<paging::Item> = sections
        .iter()
        .flat_map(|s| s.lines.iter().map(|line| (s.title.clone(), line.clone())))
        .chain(topics.map(|t| (String::new(), t.to_string())))
        .chain(
            conflicts
                .iter()
                .map(|c| (CONFLICTS_TITLE.to_string(), c.clone())),
        )
        .collect();
    let mut pages = paging::paginate(
        &items,
        max.saturating_sub(reserve),
        head,
        |title| match title.is_empty() {
            true => "\n".to_string(),
            false => heading(title),
        },
    );
    let total = pages.len();
    for (i, page) in pages.iter_mut().enumerate() {
        writeln!(page, "{}", page_footer(i + 1, total)).unwrap();
    }
    pages
}

// The conflict copies after the Index, as the first page holds them when everything fits.
pub fn conflicts_block(conflicts: &[String]) -> String {
    match conflicts.is_empty() {
        true => String::new(),
        false => format!(
            "\n\n{}\n{}",
            heading(CONFLICTS_TITLE).trim_start(),
            conflicts.join("\n")
        ),
    }
}

fn render(sections: &[Section]) -> String {
    let mut out = String::new();
    for section in sections {
        writeln!(
            out,
            "{}{}",
            heading(&section.title),
            section.lines.join("\n")
        )
        .unwrap();
    }
    out
}

#[cfg(test)]
mod tests {
    use std::fs;

    use super::*;
    use crate::config::MIN_SESSION_START_BYTES as MIN;

    #[test]
    fn lists_preferences_first_then_each_project() {
        let tmp = tempfile::tempdir().unwrap();
        let write = |path: &str, text: &str| {
            let path = tmp.path().join(path);
            fs::create_dir_all(path.parent().unwrap()).unwrap();
            fs::write(path, text).unwrap();
        };
        let note = |summary: &str| {
            format!(
                "---\ntype: user\nscope: x\nsummary: {summary}\ncreated: 2026-09-24\n---\nBody\n"
            )
        };
        write("Projects/zeta/b.md", &note("zeta note"));
        write("Projects/alpha/a.md", &note("alpha note"));
        write("Preferences/p.md", &note("a preference"));
        write("Preferences/broken.md", "no frontmatter");

        assert_eq!(
            generate(&Vault::load(tmp.path()).unwrap()),
            format!(
                "{HEADER}
## Preferences (all repos)
- [[Preferences/broken]] — (no summary)
- [[Preferences/p]] — a preference

## Projects / alpha
- [[Projects/alpha/a]] — alpha note

## Projects / zeta
- [[Projects/zeta/b]] — zeta note
"
            )
        );
    }

    fn write_notes(root: &std::path::Path, notes: &[(&str, &str)]) {
        for (path, summary) in notes {
            let path = root.join(format!("{path}.md"));
            fs::create_dir_all(path.parent().unwrap()).unwrap();
            let text = format!(
                "---\ntype: user\nscope: x\nsummary: {summary}\ncreated: 2026-09-24\n---\nBody\n"
            );
            fs::write(path, text).unwrap();
        }
    }

    #[test]
    fn the_session_view_names_notes_briefly_and_the_index_file_keeps_full_paths() {
        let tmp = tempfile::tempdir().unwrap();
        write_notes(
            tmp.path(),
            &[
                (
                    "Preferences/always-run-the-full-test-suite-before-committing",
                    "run all tests",
                ),
                (
                    "Projects/alpha/deploy-steps-for-the-staging-cluster-on-fridays",
                    "deploy",
                ),
            ],
        );
        let vault = Vault::load(tmp.path()).unwrap();
        let session = for_project(&vault, Some("alpha"));
        assert!(
            session.contains("- [[always-run-the-full]] — run all tests\n")
                && session.contains("## Projects / alpha\n- [[deploy-steps-for-the]] — deploy\n"),
            "{session}"
        );
        let file = generate(&vault);
        assert!(
            file.contains("- [[Preferences/always-run-the-full-test-suite-before-committing]] — run all tests\n"),
            "{file}"
        );
    }

    #[test]
    fn short_names_make_the_session_lines_smaller_than_full_paths() {
        let tmp = tempfile::tempdir().unwrap();
        let areas = ["billing", "search", "auth", "deploys", "docs"];
        let notes: Vec<(String, String)> = (0..100)
            .map(|i| {
                let folder = if i % 2 == 0 {
                    "Preferences".to_string()
                } else {
                    "Projects/alpha".to_string()
                };
                let path = format!(
                    "{folder}/always-check-the-w{i}-before-changing-anything-in-{}",
                    areas[i % areas.len()]
                );
                (path, format!("check w{i} first, it breaks quietly"))
            })
            .collect();
        let refs: Vec<(&str, &str)> = notes
            .iter()
            .map(|(p, s)| (p.as_str(), s.as_str()))
            .collect();
        write_notes(tmp.path(), &refs);
        let vault = Vault::load(tmp.path()).unwrap();

        let size = |lines: Vec<String>| lines.iter().map(|l| l.len() + 1).sum::<usize>();
        let short = size(
            sections(&vault, |_| true)
                .into_iter()
                .flat_map(|s| s.lines)
                .collect(),
        );
        let full = size(
            vault
                .notes
                .iter()
                .map(|n| format!("- [[{}]] — {}", n.path, n.summary().unwrap()))
                .collect(),
        );
        eprintln!("session lines: {short} bytes with short names, {full} bytes with full paths");
        assert!(short < full, "{short} >= {full}");
    }

    #[test]
    fn project_view_keeps_preferences_and_that_project() {
        let tmp = tempfile::tempdir().unwrap();
        for path in [
            "Preferences/p.md",
            "Projects/alpha/a.md",
            "Projects/zeta/b.md",
        ] {
            let path = tmp.path().join(path);
            fs::create_dir_all(path.parent().unwrap()).unwrap();
            fs::write(path, "x").unwrap();
        }
        let vault = Vault::load(tmp.path()).unwrap();
        let view = for_project(&vault, Some("alpha"));
        assert!(view.contains("[[p]]") && view.contains("[[a]]"));
        assert!(!view.contains("zeta"));
        assert!(!for_project(&vault, None).contains("Projects"));
        assert!(!view.contains("Topics"), "no topics, no topic line");
    }

    #[test]
    fn topics_are_listed_in_full_in_the_file_and_by_name_at_session_start() {
        let tmp = tempfile::tempdir().unwrap();
        for path in [
            "Preferences/p.md",
            "Topics/homelab/nas.md",
            "Topics/homelab/vpn.md",
            "Topics/work-mac/proxy.md",
        ] {
            let path = tmp.path().join(path);
            fs::create_dir_all(path.parent().unwrap()).unwrap();
            fs::write(path, "x").unwrap();
        }
        let vault = Vault::load(tmp.path()).unwrap();
        let file = generate(&vault);
        assert!(
            file.contains("\n## Topics / homelab\n- [[Topics/homelab/nas]] — (no summary)\n"),
            "{file}"
        );

        let session = for_project(&vault, None);
        assert!(!session.contains("[[Topics/"), "{session}");
        assert!(
            session.ends_with(": homelab (2), work-mac (1)\n"),
            "{session}"
        );

        let topic = for_topic(&vault, "homelab");
        assert!(
            topic.contains("[[vpn]]")
                && !topic.contains("work-mac")
                && !topic.contains("Preferences")
        );
    }

    fn section(title: &str, lines: impl Iterator<Item = String>) -> Section<'static> {
        Section {
            place: Place::Preferences,
            title: title.to_string(),
            lines: lines.collect(),
        }
    }

    fn lines_of(pages: &[String]) -> Vec<&str> {
        pages
            .iter()
            .flat_map(|p| p.lines())
            .filter(|l| l.starts_with("- "))
            .collect()
    }

    #[test]
    fn pages_hold_whole_lines_once_each_within_the_budget() {
        let first = section(
            "A",
            (0..200).map(|i| format!("- [[a/{i}]] — 日本語 🪨 {i}")),
        );
        let second = section("B", (0..150).map(|i| format!("- [[b/{i}]] — plain {i}")));
        let all: Vec<String> = [&first, &second]
            .iter()
            .flat_map(|s| s.lines.clone())
            .collect();
        for max in [MIN, MIN + 1, MIN + 2, MIN + 333] {
            let pages = pages(
                &[first.clone(), second.clone()],
                Some("Topics: x (1)"),
                &[],
                "HEAD\n",
                max,
            );
            assert!(pages.len() > 1);
            for page in &pages {
                assert!(page.len() <= max, "{} > {max}", page.len());
            }
            assert_eq!(
                lines_of(&pages),
                all.iter().map(String::as_str).collect::<Vec<_>>()
            );
            assert_eq!(
                pages.iter().filter(|p| p.contains("Topics: x (1)")).count(),
                1
            );
            assert!(pages[0].starts_with("HEAD\n"));
        }
    }

    #[test]
    fn a_continued_page_repeats_its_heading_and_the_last_page_says_so() {
        let sec = section("A", (0..400).map(|i| format!("- [[a/{i}]] — line {i}")));
        let pages = pages(&[sec], None, &[], "", MIN);
        let total = pages.len();
        assert!(total > 2);
        for (i, page) in pages.iter().enumerate() {
            assert!(page.starts_with("\n## A\n"), "{page}");
            let n = i + 1;
            let footer = page.lines().last().unwrap();
            match n < total {
                true => assert_eq!(
                    footer,
                    format!(
                        "(page {n} of {total}: call memory_index again with page={} for the next page.)",
                        n + 1
                    )
                ),
                false => assert_eq!(footer, format!("(page {n} of {total}, the last.)")),
            }
        }
    }

    #[test]
    fn a_vault_that_fits_one_page_is_one_page() {
        let sec = section("A", (0..2).map(|i| format!("- [[a/{i}]] — x")));
        assert_eq!(pages(&[sec], None, &[], "", 10_000).len(), 1);
    }

    // The pieces of a split line joined back, without headings, footers or the page head.
    fn body_of(pages: &[String], head: &str) -> String {
        pages
            .iter()
            .flat_map(|p| p.lines())
            .filter(|l| {
                !l.is_empty()
                    && !l.starts_with("## ")
                    && !l.starts_with("(page ")
                    && !head.contains(l)
            })
            .collect()
    }

    #[test]
    fn a_giant_summary_and_a_giant_topics_line_are_split_across_pages_within_the_budget() {
        let giant = format!("- [[a/giant]] — {}", "日本語🪨".repeat(300));
        let topics = format!("Topics (not loaded): {}", "homelab (1), ".repeat(200));
        let sec = section(
            "A",
            ["- [[a/1]] — short".to_string(), giant.clone()].into_iter(),
        );
        let head = "HEAD\n";
        for max in [MIN, MIN + 1, 3000] {
            let pages = pages(std::slice::from_ref(&sec), Some(&topics), &[], head, max);
            for page in &pages {
                assert!(page.len() <= max, "{} > {max}", page.len());
            }
            assert_eq!(
                body_of(&pages, head),
                format!("- [[a/1]] — short{giant}{topics}"),
                "max {max}"
            );
        }
    }

    #[test]
    fn a_long_section_title_never_costs_the_text_or_the_continuation_instruction() {
        for title_len in [250, 5000] {
            let title = "t".repeat(title_len);
            let lines: Vec<String> = (0..60)
                .map(|i| format!("- [[a/{i}]] — {}", "要約🪨".repeat(40)))
                .collect();
            let sec = section(&title, lines.clone().into_iter());
            let pages = pages(&[sec], None, &[], "", MIN);
            let total = pages.len();
            assert!(total > 2);
            for (i, page) in pages.iter().enumerate() {
                assert!(page.len() <= MIN, "{title_len}: {} > {MIN}", page.len());
                assert_eq!(page.lines().last().unwrap(), page_footer(i + 1, total));
            }
            assert_eq!(body_of(&pages, ""), lines.concat(), "title of {title_len}");
        }
    }

    #[test]
    fn a_head_that_does_not_fit_gives_way_to_a_short_header() {
        let sec = section("A", (0..5).map(|i| format!("- [[a/{i}]] — x")));
        let head = "R".repeat(5000);
        let pages = pages(&[sec], None, &[], &head, MIN);
        assert!(pages.iter().all(|p| p.len() <= MIN));
        assert!(!pages[0].contains(&head));
        assert_eq!(lines_of(&pages).len(), 5);
    }
}
